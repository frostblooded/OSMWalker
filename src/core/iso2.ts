let iso2Of: Map<string, string> | null = null;

/** The two-letter code for a three-letter one, or "". */
export function iso2(code: string): string {
  iso2Of ??= new Map(PAIRS.split(" ").map((p) => [p.slice(0, 3), p.slice(3)]));
  return iso2Of.get(code) ?? "";
}
